-- V1 — the schema as it actually exists
-- =====================================================================
--
-- Captured from a production `pg_dump --schema-only` on 19 August 2026.
--
-- WHY THIS FILE EXISTS
--
-- Until now Flyway did not own this schema. There was no V1 at all:
-- `baseline-version=1` stamped whatever Hibernate had built as "version 1"
-- and started at V2, so 59 of the 68 tables the entities need existed only
-- because `spring.jpa.hibernate.ddl-auto=update` created them at startup.
--
-- That had a consequence sharper than the drift. Every statement in V2 is
-- guarded on its table existing — it has to be, or an empty database cannot
-- start — and Flyway runs before Hibernate. So on a *fresh* database V2 found
-- nothing, applied none of its integrity repairs, and said nothing about it.
-- New environments came up without the constraints V2 exists to add.
--
-- WHAT RUNS THIS, AND WHAT DOES NOT
--
--   * A brand-new, empty database runs V1 and then V2-V9. It ends up with the
--     same schema as production, constraints included.
--   * Production and any existing database is already stamped at baseline
--     version 1, so Flyway treats V1 as applied and skips it. Nothing here is
--     executed against a database that already has these tables.
--
-- That is the whole point: this file describes what is already there, so
-- applying it to an existing database would be both unnecessary and wrong.
--
-- WHY FROM PRODUCTION RATHER THAN FROM THE ENTITIES
--
-- Hibernate can export what the entities describe, and that was the tempting
-- shortcut. But `ddl-auto=update` never drops and never narrows, so production
-- holds things the entities no longer mention — `decor_event_extras` and
-- `detail_seq` map to no entity at all, and there are four views the Java code
-- knows nothing about. A baseline from the entity export would have quietly
-- omitted every one of them, and the first fresh environment would have been
-- subtly different from production in ways nobody would notice until something
-- failed.
--
-- The consultation and calendar tables are deliberately absent: they are
-- created by V6-V9, which had not been deployed when this dump was taken.
-- =====================================================================

